/*
 * Xiaomi's P3 42 02 0a AMOLED DSI panel in the Xiaomi 17 (pudding):
 * 1220x2656, video mode, DSC at 10 bits per component, on a Novatek
 * controller.
 *
 * The tables are the vendor's power-on and power-off sequences for its
 * first 120 Hz timing, command for command except where noted; each entry
 * is the payload length followed by the DCS payload. The vendor sends
 * exit-sleep and display-on between them.
 */

