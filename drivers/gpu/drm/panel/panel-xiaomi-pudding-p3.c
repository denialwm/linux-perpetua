static void pudding_p3_send(struct mipi_dsi_multi_context *dsi_ctx,
			    const u8 *table, size_t size)
{
	size_t i;

	for (i = 0; i < size; i += 1 + table[i])
		mipi_dsi_dcs_write_buffer_multi(dsi_ctx, &table[i + 1], table[i]);
}

static int pudding_p3_power_on(struct pudding_p3 *ctx)
{
	int ret;

	/* Vendor order and settle times: vddio, vddd, then vci. */
	ret = regulator_enable(ctx->vddio);
	if (ret)
		return ret;

	ret = regulator_enable(ctx->vddd);
	if (ret)
		goto err_vddio;
	usleep_range(1000, 1500);

	ret = regulator_enable(ctx->vci);
	if (ret)
		goto err_vddd;
	usleep_range(8000, 8500);

	/*
	 * The OLED power chip of this panel variant starts from its reset,
	 * also the first time, when the bootloader has left it running.
	 */
	gpiod_set_value_cansleep(ctx->pmic_reset_gpio, 1);
	usleep_range(10000, 11000);
	gpiod_set_value_cansleep(ctx->pmic_reset_gpio, 0);
	usleep_range(10000, 11000);

	/* Vendor reset: high 1 ms, low 1 ms, high 10 ms. */
	gpiod_set_value_cansleep(ctx->reset_gpio, 0);
	usleep_range(1000, 1500);
	gpiod_set_value_cansleep(ctx->reset_gpio, 1);
	usleep_range(1000, 1500);
	gpiod_set_value_cansleep(ctx->reset_gpio, 0);
	usleep_range(10000, 11000);

	return 0;

err_vddd:
	regulator_disable(ctx->vddd);
err_vddio:
	regulator_disable(ctx->vddio);
	return ret;
}

static void pudding_p3_power_off(struct pudding_p3 *ctx)
{
	gpiod_set_value_cansleep(ctx->reset_gpio, 1);
	gpiod_set_value_cansleep(ctx->pmic_reset_gpio, 1);
	regulator_disable(ctx->vci);
	usleep_range(3000, 3500);
	regulator_disable(ctx->vddd);
	usleep_range(3000, 3500);
	regulator_disable(ctx->vddio);
}

static int pudding_p3_on(struct pudding_p3 *ctx)
{
	struct mipi_dsi_multi_context dsi_ctx = { .dsi = ctx->dsi };

	pudding_p3_send(&dsi_ctx, pudding_p3_init, sizeof(pudding_p3_init));
	mipi_dsi_dcs_exit_sleep_mode_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 120);
	pudding_p3_send(&dsi_ctx, pudding_p3_awake, sizeof(pudding_p3_awake));
	mipi_dsi_dcs_set_display_on_multi(&dsi_ctx);
	pudding_p3_send(&dsi_ctx, pudding_p3_lit, sizeof(pudding_p3_lit));

	return dsi_ctx.accum_err;
}

static int pudding_p3_off(struct pudding_p3 *ctx)
{
	struct mipi_dsi_multi_context dsi_ctx = { .dsi = ctx->dsi };

	pudding_p3_send(&dsi_ctx, pudding_p3_leave, sizeof(pudding_p3_leave));
	mipi_dsi_dcs_set_display_off_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 30);
	mipi_dsi_dcs_enter_sleep_mode_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 120);

	return dsi_ctx.accum_err;
}

static int pudding_p3_prepare(struct drm_panel *panel)
{
	struct pudding_p3 *ctx = to_pudding_p3(panel);
	struct device *dev = &ctx->dsi->dev;
	struct drm_dsc_picture_parameter_set pps;
	u8 mode;
	int ret;

	ret = pudding_p3_power_on(ctx);
	if (ret)
		return ret;

	/* The vendor sends the power-on sequence in low-power mode. */
	ctx->dsi->mode_flags |= MIPI_DSI_MODE_LPM;

	ret = pudding_p3_on(ctx);
	if (ret < 0) {
		dev_err(dev, "failed to initialise panel: %d\n", ret);
		goto err;
	}

	/*
	 * As downstream does, the PPS follows the power-on sequence: its
	 * decoder writes (0x91) do not match the stream, and the PPS
	 * replaces them.
	 */
	drm_dsc_pps_payload_pack(&pps, &ctx->dsc);
	ret = mipi_dsi_picture_parameter_set(ctx->dsi, &pps);
	if (ret < 0) {
		dev_err(dev, "failed to send PPS: %d\n", ret);
		goto err;
	}

	ret = mipi_dsi_dcs_get_power_mode(ctx->dsi, &mode);
	if (ret < 0)
		dev_warn(dev, "failed to read power mode: %d\n", ret);
	else
		dev_info(dev, "power mode 0x%02x\n", mode);

	ctx->dsi->mode_flags &= ~MIPI_DSI_MODE_LPM;
	return 0;

err:
	ctx->dsi->mode_flags &= ~MIPI_DSI_MODE_LPM;
	pudding_p3_power_off(ctx);
	return ret;
}

static int pudding_p3_unprepare(struct drm_panel *panel)
{
	struct pudding_p3 *ctx = to_pudding_p3(panel);
	int ret;

	/* The vendor sends the power-off sequence in high-speed mode. */
	ret = pudding_p3_off(ctx);
	if (ret < 0)
		dev_err(&ctx->dsi->dev, "failed to power down panel: %d\n", ret);

	pudding_p3_power_off(ctx);
	return 0;
}

