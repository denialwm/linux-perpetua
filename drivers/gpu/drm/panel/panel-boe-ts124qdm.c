static void ts124qdm_send(struct mipi_dsi_multi_context *dsi_ctx,
			  const u8 *table, size_t size)
{
	size_t i;

	for (i = 0; i < size; i += 1 + table[i])
		mipi_dsi_dcs_write_buffer_multi(dsi_ctx, &table[i + 1], table[i]);
}

/*
 * Samsung's panel_reset supply, switched late (samsung,aot_reset_regulator_late:
 * once the DSI link is up): 5 ms, then qcom,mdss-dsi-reset-sequence <1 5 0 4 1 12>,
 * then 1 ms. Reset also restarts the touch half of the chip, which then waits
 * for its firmware again.
 */
static void ts124qdm_reset(struct ts124qdm *ctx)
{
	usleep_range(5000, 5100);
	gpiod_set_value_cansleep(ctx->reset_gpio, 0);
	usleep_range(5000, 5100);
	gpiod_set_value_cansleep(ctx->reset_gpio, 1);
	usleep_range(4000, 4100);
	gpiod_set_value_cansleep(ctx->reset_gpio, 0);
	usleep_range(13000, 13100);
}

static int ts124qdm_prepare(struct drm_panel *panel)
{
	struct ts124qdm *ctx = to_ts124qdm(panel);
	struct mipi_dsi_multi_context dsi_ctx = { .dsi = ctx->dsi };
	int ret;

	/* Samsung's supply order: panel_boost_en (post-on 1 ms) before panel_reset. */
	ret = regulator_enable(ctx->boost);
	if (ret)
		return ret;

	ts124qdm_reset(ctx);

	ts124qdm_send(&dsi_ctx, ts124qdm_init, sizeof(ts124qdm_init));
	mipi_dsi_dcs_exit_sleep_mode_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 128);
	mipi_dsi_dcs_set_display_on_multi(&dsi_ctx);
	mipi_dsi_dcs_set_tear_on_multi(&dsi_ctx, MIPI_DSI_DCS_TEAR_MODE_VBLANK);
	mipi_dsi_msleep(&dsi_ctx, 32);

	if (dsi_ctx.accum_err) {
		regulator_disable(ctx->boost);
		gpiod_set_value_cansleep(ctx->reset_gpio, 1);
		return dsi_ctx.accum_err;
	}

	return 0;
}

/*
 * The boost goes off first, as Samsung's "boost_en early off" at backlight 0: the panel's PWM must
 * not stop while the boost still runs (reverse voltage at the boost output). Then
 * qcom,mdss-dsi-pre-off-command and -off-command, then panel_reset off after its 90 ms.
 */
static int ts124qdm_unprepare(struct drm_panel *panel)
{
	struct ts124qdm *ctx = to_ts124qdm(panel);
	struct mipi_dsi_multi_context dsi_ctx = { .dsi = ctx->dsi };

	regulator_disable(ctx->boost);
	mipi_dsi_dcs_set_display_off_multi(&dsi_ctx);
	mipi_dsi_dcs_enter_sleep_mode_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 32);
	if (dsi_ctx.accum_err)
		dev_err(&ctx->dsi->dev, "failed to power down panel: %d\n",
			dsi_ctx.accum_err);

	msleep(90);
	gpiod_set_value_cansleep(ctx->reset_gpio, 1);
	usleep_range(1000, 1100);

	return 0;
}

