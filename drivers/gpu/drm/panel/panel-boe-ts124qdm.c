/*
 * BOE TS124QDM: the 12.4" 1600x2560 LCD of the Samsung Galaxy Tab S7 FE
 * (gts7xllite), on a FocalTech FT8203 touch and display controller. Video
 * mode, four lanes, DSC 1.1 at 8 bits per component and 8 bits per pixel,
 * two 800x40 slices per line.
 *
 * Everything here comes from Samsung's tree for the tablet (board revision 7,
 * gts7xllite_eur_openx_w00_r05.dts, node ss_dsi_panel_FT8203_TS124QDM_WQXGA)
 * and its panel file (techpack/display/msm/samsung/FT8203_TS124QDM):
 * - The init table is qcom,mdss-dsi-on-command, command for command, up to
 *   exit-sleep; each entry is the payload length followed by the payload.
 *   Samsung sends them as DCS long writes; two-byte ones go out here as DCS
 *   short writes with a parameter, as mainline sends them.
 * - Samsung sets samsung,no_qcom_pps: the panel never gets a PPS (or a
 *   compression mode command), its decoder is set up by the init table.
 * - Samsung's sequences are sent in low-power mode, brightness included.
 *
 * The driver switches the 5 V backlight boost (boost-supply, the MAX77816 on
 * gpio72) and the reset line (Samsung's panel_reset, gpio73). The other panel
 * supplies (pm6350 L14 for VDDI, the ISL98608 +-5.6 V buck on gpio88/89) stay
 * as the bootloader left them: Samsung reprograms the buck over I2C after each
 * power-on, and it has no driver yet. This tablet has no LP8558 (no node in
 * the rev7 tree), so the boost is the whole backlight power path.
 */

